% --- Executes on button press in capture_button.
function capture_button_Callback(hObject, eventdata, handles)
% hObject    handle to capture_button (see GCBO)
% eventdata  reserved - to be defined in a future version of MATLAB
% handles    structure with handles and user data (see GUIDATA)

%convert the video once captured into a string of .tif files
% vid_path = get(handles.savepath,'string');
% set(handles.pathbox,'string',vid_path);
% avitif(vid_path)

% --- Executes on button press in process_button.
function process_button_Callback(hObject, eventdata, handles)
% hObject    handle to process_button (see GCBO)
% eventdata  reserved - to be defined in a future version of MATLAB
% handles    structure with handles and user data (see GUIDATA)

%choose what file to analyse
if get(handles.use_last_captured_button,'value') == 0
    vid_path = get(handles.pathbox,'string');
else
    vid_path = get(handles.savepath,'string');
    set(handles.pathbox,'string',vid_path);
end

%choose how much of it to analyse. Only convert what is needed
if get(handles.contiguous_analysis_button,'value') == 1
    avitif(vid_path,'n',0);
else
    max_frames = str2double(get(handles.batch_size,'string'));
    avitif(vid_path,'y',max_frames);
end

%read analysis parameters from input boxes
minsteps = str2double(get(handles.minsteps_box,'string'));
sterr = str2double(get(handles.maxerr_box,'string'));
pxptch = str2double(get(handles.custom_pixel_box,'string'));
if get(handles.contiguous_analysis_button,'value') == 0
    frames = str2double(get(handles.batch_size,'string'));
else
    frames = 10;%switch later for full filesize
end

raw_matrix = accuracy(input_transformer('frame','.tif',1,frames,100),minsteps,sterr);
size_matrix = sizecor(raw_matrix,pxptch);

%and splurge the two matrices together, replacing arbitrary path lengths
%with pixel-size corrected values
full_matrix = zeros(length(size_matrix(:,1)),3);
for i = 1 : length(size_matrix(:,1))
    full_matrix(i,1) = size_matrix(i,1);
    full_matrix(i,2) = size_matrix(i,2);
    full_matrix(i,3) = raw_matrix(i,3);
end

%strip out particles smaller than minimum expected
min_size = str2double(get(handles.min_particle_size,'string'));
len = length(full_matrix); %makes things easier later
for t = 1 : length(full_matrix)-1
    if full_matrix(len-t+1,1)<min_size
        full_matrix(len-t+1,:) = [];
    end
end

%write output data to csv file
[filename,pathname,filter] = uiputfile('.csv');
% fileID = fopen(strcat(pathname,filename),'wt');
% for p = 1 : length(full_matrix(:,1))
%     fprintf(fileID,'\n%d,%d,%d,%d',full_matrix(p,:));
% end
% fclose(fileID);
csvwrite(strcat(pathname,filename),full_matrix);
%this leaves an output of columns size, standard error, and track length

%and set this path to be the default .csv file location for the output
%section
set(handles.output_path,'string',strcat(pathname,filename));

%delete video files from scratch directory
for q = 1 : frames
    delete(strcat('frame',num2str(q),'.tif'));
end

%and do an automatic plot of the output data in the output window
histogram_auto = autohist(full_matrix(:,1));
bar(handles.output_histogram,histogram_auto(:,1),histogram_auto(:,2));

guidata(hObject,handles);



