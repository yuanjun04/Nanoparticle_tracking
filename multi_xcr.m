function mxcr = multi_xcr(particles,xdim,ydim,radius,iterations,frames,type)

%this does the same as 'multi_van_hove', only it calls xcr using the xcorr2
%function rather than using the home-grown correlation function. It is not
%very efficient with RAM - processing 15 frames at 640x480 resolution
%requires at least 6GB of free RAM. It gives the option to use either
%single or double precision floats. The RAM requirement is estimated for
%single precision floats only. The 'type' variable needs to be either
%'single' or 'double'.

%this allows for the face that there will be about 6 frames-worth of data
%truncated in the later data-smoothing and post-processing.
frames = frames+6;

%This checks that the first frame indexed isn't in fact numbered zero = if
%it is, then the frame indices are all increased by one such that the
%parser can use the raw frame indices as matlab array indices.
if particles(1,1) == 0
    particles(:,1) = particles(:,1)+1;
end

%a first case is calculated. The selection of data to be used for a given
%iteration number is generated by the sample_gen function, which takes 4
%arguments: full array of particle data, number of iterations, number of
%current iteration, and the number of frames to be considered in that
%iteration.
sample = sample_gen(particles,iterations,1,frames);
multi_xcr_sum = xcr(sample,xdim,ydim,radius,type);

%this loop evaluates the rest of the iterations
%this loop also seems to be creating arbitrary infinities.
for p = 2 : iterations
    sample = sample_gen(particles,iterations,p,frames);
    single_xcr = xcr(sample,xdim,ydim,radius,type);
    %not all iterations will produce identically-lengthed outputs. These
    %conditional statements allow for this, by weighting the different
    %iterations in a fair way and averaging them into the final sum. The
    %mathematics of the average should be perfectly fair.
    if length(single_xcr) >= length(multi_xcr_sum)
        for j = 1 : length(multi_xcr_sum)
            multi_xcr_sum(j) = ((multi_xcr_sum(j)*(p-1))/p)+(single_xcr(j)/p);
        end
    else
        for l = 1 : length(single_xcr)
            multi_xcr_sum(l) = ((multi_xcr_sum(l)*(p-1))/p)+(single_xcr(l)/p);
        end
        %this is not nercessarily the most fair way of handling this case.
        %A better means may be by truncating whichever array is longer.
        for k = length(single_xcr) : length(multi_xcr_sum)
            %multi_hove_sum(k) = (multi_hove_sum(k)*(p-1))/p;
            try
                multi_xcr_sum(length(single_xcr)) = [];
            catch
                fprintf('Failed output truncation');
            end
        end
    end
end

%smooth the data into a nicer curve
multi_xcr_sum = smooth(smooth(multi_xcr_sum));

%this removes the first six datapoints, thus annhiliating the deleterious
%effect of the smoothing functions on the endpoint. The final endpoint
%isn't reated in a similar way to maximise processing efficiency, since in
%the calculation of a decay constant, a small anomaly at the low end isn't 
multi_xcr_sum(1:6) = [];

%and then return the output array!
mxcr = multi_xcr_sum;
end